#!/usr/bin/env python3
"""make_sample.py - seeded validation sample for the Diary pipeline (spec section 9). Read-only on Text\\; writes SAMPLE-SET.md and sample-set.json beside itself.
Usage: make_sample.py [--root <Diary dir>] [--seed 20261113]   Sentence split is naive (abbreviations guarded); the real S2 chunker supersedes it."""
import argparse, json, random, re
from pathlib import Path
ap = argparse.ArgumentParser(); ap.add_argument("--root", default=str(Path(__file__).resolve().parent.parent)); ap.add_argument("--seed", type=int, default=20261113)
a = ap.parse_args(); root = Path(a.root); rnd = random.Random(a.seed)
EPS = [(1,"1-2","2-5"),(2,"2-6","2-21"),(3,"2-22","2-36"),(4,"2-37","2-50"),(5,"2-51","2-64"),(6,"2-65","2-79"),(7,"2-80","2-94"),(8,"2-95","3-1"),(9,"3-2","3-17"),
       (10,"3-18","3-32"),(11,"3-33","3-46"),(12,"3-48","3-60"),(13,"3-62","3-76"),(14,"3-78","3-88"),(15,"3-90","3-102"),(16,"3-104","3-108")]
def key(p): n, m = p.split("-"); return int(n)*1000 + int(m)
def episode(p):
    for e, s, t in EPS:
        if key(s) <= key(p) <= key(t): return e
pages = sorted({f.stem for f in (root/"Text"/"PL").glob("*.txt") if re.fullmatch(r"\d-\d+", f.stem) and episode(f.stem)}, key=key)
ABBR = r"(?<!\bkpt)(?<!\bpor)(?<!\bgen)(?<!\bmjr)(?<!\bp)(?<!\bpł)(?<!\bpłk)(?<!\bkpr)(?<!\bsierż)(?<!\bdr)(?<!\bnr)(?<!\bSt)(?<!\bMr)(?<!\bCpl)(?<!\bLt)(?<!\bCapt)(?<!\bMaj)(?<!\bGen)(?<!\bMrs)(?<!\bSgt)"
SPLIT = re.compile(ABBR + r"(?<=[.!?])\s+(?=[A-ZŁŚŻŹĆŃÓĄĘ„\"“0-9])")
def sentences(lang):
    out = []
    for p in pages:
        t = " ".join((root/"Text"/lang/f"{p}.txt").read_text(encoding="utf-8", errors="replace").split())
        for i, s in enumerate(SPLIT.split(t)):
            if s.strip(): out.append({"lang": lang, "page": p, "episode": episode(p), "idx": i, "chars": len(s), "text": s.strip()})
    return out
res = {"seed": a.seed, "pages": len(pages), "random": [], "hard": []}
NAMES = ["Otwock","Hendaye","Habowski","Harbowski","Gigondes","Gigadas","Sadecki","Sodecki","Tryjest","Modan","Zyrkiewicz","Winogradzki","Winogrodzki"]
for lang in ("PL", "EN"):
    S = sentences(lang); res[f"n_{lang}"] = len(S)
    eps = rnd.sample(range(1, 17), 8)                        # 8 distinct episodes, one random sentence each (stratified across the series)
    for e in eps:
        c = [s for s in S if s["episode"] == e and 40 <= s["chars"] <= 230]; res["random"].append(dict(rnd.choice(c), kind="random"))
    seen = set()
    def add(cands, why, n):
        k = 0
        for s in cands:
            kk = (s["lang"], s["page"], s["idx"])
            if kk in seen: continue
            seen.add(kk); res["hard"].append(dict(s, kind="hard", why=why)); k += 1
            if k >= n: break
    add(sorted(S, key=lambda s: -s["chars"]), "longest sentence", 4)
    add([s for s in S if re.search(r"\d{3,}|\d+,\d+", s["text"]) and s["chars"] < 230], "numerals", 4)
    add([s for s in S if re.search(r"\d{1,2}\s*(?:th|\.)?\s*(?:Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec|stycz|lut|mar|kwie|maj|czerw|lip|sierp|wrze|paźdz|listop|grud)", s["text"])], "date in sentence", 3)
    add([s for s in S if "...." in s["text"] or "…" in s["text"]], "gap/ellipsis", 2)
    add([s for s in S if re.search(r"[„“\"][^„“\"]{15,}[”“\"]", s["text"])], "quotation", 2)
    for n in NAMES: add([s for s in S if n in s["text"] and s["chars"] < 230], f"name: {n}", 1)
json.dump(res, open(Path(__file__).with_name("sample-set.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
L = [f"---\ntitle: Pipeline validation sample set\nstatus: draft for Jim\ncreated: 2026-11-13\ntags: [diary, pipeline, sample]\n---",
     f"# Validation sample (seed {a.seed})", "Generated by `pipeline\\make_sample.py` from `Text\\PL` and `Text\\EN` ({} pages, Eps 1-16; naive sentence split: PL {}, EN {}). Spec: [[Diary/PIPELINE-SPEC]] section 9. The random picks are one sentence from each of 8 randomly chosen episodes per language; the hard cases are picked by rule. Edit by hand if Jim wants others; the S2 chunker will replace the naive split.".format(len(pages), res["n_PL"], res["n_EN"]),
     "\n## Random sample (8 PL + 8 EN)\n| lang | ep | page | # | chars | text |\n|---|---|---|---|---|---|"]
for s in res["random"]: L.append(f"| {s['lang']} | {s['episode']} | {s['page']} | {s['idx']} | {s['chars']} | {s['text'][:150].replace('|','/')}{'...' if s['chars']>150 else ''} |")
L += ["\n## Hard cases\n| lang | why | ep | page | # | chars | text |\n|---|---|---|---|---|---|---|"]
for s in res["hard"]: L.append(f"| {s['lang']} | {s['why']} | {s['episode']} | {s['page']} | {s['idx']} | {s['chars']} | {s['text'][:150].replace('|','/')}{'...' if s['chars']>150 else ''} |")
Path(__file__).with_name("SAMPLE-SET.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print(len(res["random"]), "random,", len(res["hard"]), "hard;", res["n_PL"], "PL /", res["n_EN"], "EN sentences")
